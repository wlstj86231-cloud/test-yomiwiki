// Copies public/knowledge.css into functions/_lib/css.js so Functions can inline it (no render-blocking request).
// Run after editing public/knowledge.css:  node scripts/sync-css.mjs
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const css = fs.readFileSync(path.join(root, 'public', 'knowledge.css'), 'utf8').replace(/\r\n/g, '\n');
const min = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n\s*/g, '').trim();
fs.writeFileSync(path.join(root, 'functions', '_lib', 'css.js'), `// Generated by scripts/sync-css.mjs from public/knowledge.css — do not edit by hand.\nexport const CSS = ${JSON.stringify(min)};\n`);
console.log(`css.js written (${min.length} chars)`);
